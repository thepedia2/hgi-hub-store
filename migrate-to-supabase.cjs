const { DatabaseSync } = require('node:sqlite');
const { Client } = require('pg');

const sqlite = new DatabaseSync('hgi-hub.sqlite');

if (!process.env.DATABASE_URL) {
  console.error('DATABASE_URL belum ditemukan di .env');
  process.exit(1);
}

const pg = new Client({
  connectionString: process.env.DATABASE_URL,
  ssl: { rejectUnauthorized: false }
});

async function main() {
  await pg.connect();

  console.log('Terhubung ke Supabase PostgreSQL.');

  await pg.query(`
    CREATE TABLE IF NOT EXISTS users (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      email TEXT UNIQUE NOT NULL,
      phone TEXT NOT NULL,
      password_hash TEXT NOT NULL,
      verified INTEGER NOT NULL DEFAULT 0,
      verification_code TEXT,
      verification_expires INTEGER,
      created_at TEXT NOT NULL
    );

    CREATE TABLE IF NOT EXISTS orders (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      code TEXT UNIQUE NOT NULL,
      user_email TEXT NOT NULL,
      game_id TEXT NOT NULL,
      nickname TEXT NOT NULL,
      payment TEXT NOT NULL,
      items_json TEXT NOT NULL,
      total_m INTEGER NOT NULL,
      price_total INTEGER NOT NULL,
      unique_code INTEGER NOT NULL,
      total_pay INTEGER NOT NULL,
      status TEXT NOT NULL DEFAULT 'pending',
      created_at TEXT NOT NULL
    );

    CREATE TABLE IF NOT EXISTS sell_orders (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      code TEXT UNIQUE NOT NULL,
      user_email TEXT NOT NULL,
      amount_b INTEGER NOT NULL,
      sender_id TEXT NOT NULL,
      bank TEXT NOT NULL,
      account_number TEXT NOT NULL,
      account_name TEXT NOT NULL,
      status TEXT NOT NULL DEFAULT 'pending',
      created_at TEXT NOT NULL
    );

    CREATE TABLE IF NOT EXISTS transactions (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_email TEXT NOT NULL,
      kind TEXT NOT NULL,
      reference_code TEXT NOT NULL,
      product_label TEXT NOT NULL,
      amount INTEGER NOT NULL,
      created_at TEXT NOT NULL
    );
  `);

  const tables = ['users', 'orders', 'sell_orders', 'transactions'];

  for (const table of tables) {
    const rows = sqlite.prepare(`SELECT * FROM ${table}`).all();

    console.log(`${table}: ${rows.length} data ditemukan.`);

    if (rows.length === 0) continue;

    for (const row of rows) {
      const columns = Object.keys(row);
      const values = Object.values(row);

      const placeholders = values.map((_, i) => `$${i + 1}`).join(', ');
      const columnList = columns.map(c => `"${c}"`).join(', ');

      await pg.query(
        `INSERT INTO "${table}" (${columnList})
         VALUES (${placeholders})
         ON CONFLICT DO NOTHING`,
        values
      );
    }
  }

  for (const table of tables) {
    await pg.query(`
      SELECT setval(
        pg_get_serial_sequence('"${table}"', 'id'),
        COALESCE((SELECT MAX(id) FROM "${table}"), 1),
        true
      )
    `);
  }

  console.log('');
  console.log('================================');
  console.log('MIGRASI BERHASIL');
  console.log('================================');

  for (const table of tables) {
    const result = await pg.query(`SELECT COUNT(*)::int AS count FROM "${table}"`);
    console.log(`${table}: ${result.rows[0].count} data`);
  }

  await pg.end();
}

main().catch(async error => {
  console.error('');
  console.error('MIGRASI GAGAL:');
  console.error(error.message);

  try {
    await pg.end();
  } catch {}

  process.exit(1);
});
