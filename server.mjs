app.post('/api/register', async (req, res) => {
  try {
    const email = cleanEmail(req.body?.email);
    const phone = String(req.body?.phone || '').trim();
    const password = String(req.body?.password || '');

    if (!/^\S+@\S+\.\S+$/.test(email)) {
      return res.status(400).json({
        message: 'Email belum valid.'
      });
    }

    if (!validPhone(phone)) {
      return res.status(400).json({
        message: 'Nomor HP belum valid.'
      });
    }

    if (password.length < 6) {
      return res.status(400).json({
        message: 'Password minimal 6 karakter.'
      });
    }

    const existing = await findUser(email);

    if (existing?.verified) {
      return res.status(409).json({
        message: 'Email sudah terdaftar. Silakan login.'
      });
    }

    const code = String(
      crypto.randomInt(100000, 1000000)
    );

    const expires = Date.now() + 600000;

    await pool.query(
      `INSERT INTO users (
        email,
        phone,
        password_hash,
        verified,
        verification_code,
        verification_expires,
        created_at
      )
      VALUES ($1, $2, $3, 0, $4, $5, $6)
      ON CONFLICT (email)
      DO UPDATE SET
        phone = EXCLUDED.phone,
        password_hash = EXCLUDED.password_hash,
        verification_code = EXCLUDED.verification_code,
        verification_expires = EXCLUDED.verification_expires`,
      [
        email,
        phone,
        hashPassword(password),
        code,
        expires,
        now()
      ]
    );

    const smtp =
      process.env.SMTP_HOST &&
      process.env.SMTP_USER &&
      process.env.SMTP_PASS &&
      process.env.MAIL_FROM;

    if (!smtp) {
      return res.status(201).json({
        message:
          'Pendaftaran tersimpan. Gunakan kode demo untuk verifikasi lokal.',
        devCode: code
      });
    }

    try {
      const transporter = nodemailer.createTransport({
        host: process.env.SMTP_HOST,
        port: Number(process.env.SMTP_PORT || 587),
        secure:
          String(process.env.SMTP_SECURE).toLowerCase() === 'true',
        auth: {
          user: process.env.SMTP_USER,
          pass: process.env.SMTP_PASS
        }
      });

      await transporter.sendMail({
        from: process.env.MAIL_FROM,
        to: email,
        subject: 'Kode verifikasi HGI Hub',
        text: `Kode verifikasi HGI Hub Anda: ${code}`
      });

      res.status(201).json({
        message: 'Kode verifikasi telah dikirim ke email Anda.'
      });
    } catch (e) {
      console.error('SMTP ERROR:', e.message);

      res.status(502).json({
        message: 'Email verifikasi gagal dikirim.'
      });
    }
  } catch (e) {
    console.error('REGISTER ERROR:', e);

    res.status(500).json({
      message: 'Terjadi kesalahan saat mendaftar.'
    });
  }
});

