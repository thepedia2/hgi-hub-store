const whatsappNumber = () =>
  String(
    process.env.WHATSAPP_ADMIN_NUMBER || ''
  ).replace(/\D/g, '');

const whatsappUrl = message =>
  `https://wa.me/${whatsappNumber()}?text=${encodeURIComponent(
    message
  )}`;

const sendWhatsApp = async (req, res) => {
  const message =
    String(req.body?.message || '').trim();

  if (message.length < 3) {
    return res.status(400).json({
      message: 'Pesan WhatsApp belum diisi.'
    });
  }

  if (
    !(
      process.env.WHATSAPP_ACCESS_TOKEN &&
      process.env.WHATSAPP_PHONE_NUMBER_ID
    )
  ) {
    return res.json({
      ok: true,
      mode: 'click-to-chat',
      url: whatsappUrl(message),
      message: 'WhatsApp siap dibuka.'
    });
  }

  try {
    const version =
      process.env.WHATSAPP_API_VERSION || 'v22.0';

    const response = await fetch(
      `https://graph.facebook.com/${version}/${process.env.WHATSAPP_PHONE_NUMBER_ID}/messages`,
      {
        method: 'POST',
        headers: {
          Authorization:
            `Bearer ${process.env.WHATSAPP_ACCESS_TOKEN}`,
          'Content-Type': 'application/json'
        },
        body: JSON.stringify({
          messaging_product: 'whatsapp',
          to: whatsappNumber(),
          type: 'text',
          text: {
            preview_url: false,
            body: message
          }
        })
      }
    );

    const data =
      await response.json().catch(() => ({}));

    if (!response.ok) {
      return res.status(502).json({
        message:
          'WhatsApp API gagal mengirim pesan.',
        detail: data.error?.message
      });
    }

    res.json({
      ok: true,
      mode: 'cloud-api',
      sent: true,
      message:
        'Pesan berhasil dikirim ke admin.'
    });
  } catch (e) {
    console.error('WHATSAPP ERROR:', e);

    res.status(502).json({
      message:
        'WhatsApp API tidak dapat dihubungi.'
    });
  }
};

